#!/usr/bin/env python3
"""Generate middleware/steamworks/steam_api_stub.c from Steamworks.NET's decompiled NativeMethods.cs.

Every steam_api entry point the managed wrapper can call gets a C definition so P/Invoke never hits
EntryPointNotFoundException. Defaults return 0; OVERRIDES makes Init succeed with a logged-on user.
Entry points defined in the hand-written middleware/steamworks/steam_api_runtime.c are skipped.
usage: gen-steam-stub.py <NativeMethods.cs> <steam_api_runtime.c> <out.c>
"""
import re, sys

OVERRIDES = {
    'SteamAPI_GetHSteamPipe': 'return 1;',
    'SteamAPI_GetHSteamUser': 'return 1;',
    'SteamAPI_IsSteamRunning': 'return 1;',
    'SteamInternal_CreateInterface': 'return (uint64_t)(uintptr_t)bpp_steam_iface;',
    'SteamInternal_FindOrCreateUserInterface': 'return (uint64_t)(uintptr_t)bpp_steam_iface;',
    'SteamAPI_ISteamApps_BIsSubscribed': 'return 1;',
    'SteamAPI_ISteamApps_BIsSubscribedApp': 'return 1;',
    'SteamAPI_ISteamApps_GetCurrentGameLanguage': 'return (uint64_t)(uintptr_t)"english";',
    'SteamAPI_ISteamApps_GetAvailableGameLanguages': 'return (uint64_t)(uintptr_t)"english";',
    'SteamAPI_ISteamUtils_GetSteamUILanguage': 'return (uint64_t)(uintptr_t)"english";',
    'SteamAPI_ISteamFriends_GetPersonaName': 'return (uint64_t)(uintptr_t)"iOS Player";',
    'SteamAPI_ISteamUtils_GetIPCountry': 'return (uint64_t)(uintptr_t)"US";',
}
# Interface accessors (SteamAPI_SteamUser_v023, SteamAPI_ISteamClient_GetISteamUser, ...) must be non-null.
IFACE = re.compile(r'^(SteamAPI_Steam\w+_v\d+|SteamAPI_ISteamClient_GetISteam\w+|SteamAPI_SteamGameServer\w*_v\d+)$')

def main(src, runtime, out):
    text = open(src, encoding='utf-8').read()
    handwritten = set(re.findall(r'^API \w+ (\w+)\(', open(runtime).read(), re.M))
    names = []
    for m in re.finditer(r'\[DllImport\("steam_api"[^\]]*?\)\]\s*(?:\[return:[^\]]*\]\s*)?public static extern [^(]*?(\w+)\(', text):
        ep = re.search(r'EntryPoint = "(\w+)"', m.group(0))
        names.append(ep.group(1) if ep else m.group(1))
    names = sorted(set(names) - handwritten)
    lines = ['// Generated by middleware/steamworks/generate-stub.py from Steamworks.NET NativeMethods. Do not edit.',
             '// A Steam client cannot run on iOS; these stubs let the game boot without one.',
             '#include <stdint.h>', '#define API __attribute__((visibility("default"), used))',
             'static uint64_t bpp_steam_iface[64];', '']
    for n in names:
        body = OVERRIDES.get(n) or ('return (uint64_t)(uintptr_t)bpp_steam_iface;' if IFACE.match(n) else 'return 0;')
        lines.append(f'API uint64_t {n}(void) {{ {body} }}')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(names)} steam_api entry points -> {out}')

if __name__ == '__main__':
    main(*sys.argv[1:])
