#!/usr/bin/env python3
"""Export the desktop app icon as the Android App's adaptive launcher icon.

The desktop icon (bazaarplusplus-installer/src-tauri/icons/app-icon.png) is
artwork on a dark squircle whose fill is a vertical gradient.
An adaptive icon needs two layers that the launcher masks itself, so:

- background: the squircle's gradient, extended over the whole 108dp layer;
- foreground: the icon with the squircle's rim feathered away, scaled so the
  artwork fits the 66dp safe zone every launcher mask keeps.

Both are written for every density as res/mipmap-*/ic_launcher_{background,foreground}.png,
and res/mipmap-anydpi/ic_launcher.xml records the source's sha256, which
`just design::check` compares with the desktop icon to catch a stale export.

    python3 tools/launcher-icon.py   (needs Pillow; `just android::launcher-icon`)
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'bazaarplusplus-installer/src-tauri/icons/app-icon.png'
RES = ROOT / 'app/src/main/res'
ADAPTIVE = RES / 'mipmap-anydpi/ic_launcher.xml'
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
LAYER_DP = 108
SAFE_RADIUS_DP = 33
# Rows and columns of the source that are squircle fill, not rim or artwork,
# for fitting the gradient: the left margin between the rim and the artwork.
FILL_COLUMNS = range(60, 90)
FILL_ROWS = range(220, 820)


def digest() -> str:
    return hashlib.sha256(SOURCE.read_bytes()).hexdigest()


def adaptive_xml(sha: str) -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The desktop app icon as an adaptive icon, generated by tools/launcher-icon.py from
     bazaarplusplus-installer/src-tauri/icons/app-icon.png (sha256 {sha}).
     Do not edit: re-run the script when the desktop icon changes. Themed icons use the
     flat brand mark. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@mipmap/ic_launcher_background" />
  <foreground android:drawable="@mipmap/ic_launcher_foreground" />
  <monochrome android:drawable="@drawable/bpp_launcher_monochrome" />
</adaptive-icon>
'''


def export() -> None:
    from PIL import Image, ImageDraw, ImageFilter

    icon = Image.open(SOURCE).convert('RGBA')
    size = icon.width
    pixels = icon.load()

    # The fill is a vertical gradient; fit each channel as a + b * y.
    samples = [(y, pixels[x, y][:3]) for y in FILL_ROWS for x in FILL_COLUMNS]
    n = len(samples)
    mean_y = sum(y for y, _ in samples) / n
    fit = []
    for channel in range(3):
        mean_c = sum(c[channel] for _, c in samples) / n
        slope = sum((y - mean_y) * (c[channel] - mean_c) for y, c in samples) / sum((y - mean_y) ** 2 for y, _ in samples)
        fit.append((mean_c - slope * mean_y, slope))

    def fill(y: float) -> tuple:
        return tuple(max(0, min(255, round(a + b * y))) for a, b in fit)

    # The artwork: everything that differs clearly from the fill, inside the rim.
    inset = size // 16
    art = [(x, y) for y in range(inset, size - inset, 2) for x in range(inset, size - inset, 2)
           if max(abs(p - q) for p, q in zip(pixels[x, y][:3], fill(y))) > 24]
    left, right = min(x for x, _ in art), max(x for x, _ in art)
    top, bottom = min(y for _, y in art), max(y for _, y in art)
    cx, cy = (left + right) / 2, (top + bottom) / 2
    reach = max(((x - cx) ** 2 + (y - cy) ** 2) ** 0.5 for x, y in art)

    # Feather the squircle's rim away so only fill and artwork remain.
    mask = Image.new('L', icon.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((inset, inset, size - inset, size - inset), radius=size // 6, fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(size // 48))
    foreground = icon.copy()
    foreground.putalpha(Image.composite(icon.getchannel('A'), Image.new('L', icon.size, 0), mask))

    for name, density in DENSITIES.items():
        layer = round(LAYER_DP * density)
        scale = SAFE_RADIUS_DP * density / reach
        art_size = round(size * scale)
        offset = (round(layer / 2 - cx * scale), round(layer / 2 - cy * scale))

        front = Image.new('RGBA', (layer, layer), (0, 0, 0, 0))
        front.alpha_composite(foreground.resize((art_size, art_size), Image.LANCZOS), offset)
        back = Image.new('RGB', (layer, layer))
        for y in range(layer):
            back.paste(fill((y - offset[1]) / scale), (0, y, layer, y + 1))

        folder = RES / f'mipmap-{name}'
        folder.mkdir(exist_ok=True)
        front.save(folder / 'ic_launcher_foreground.png', optimize=True)
        back.save(folder / 'ic_launcher_background.png', optimize=True)

    ADAPTIVE.write_text(adaptive_xml(digest()))
    print(f'Exported the launcher icon from {SOURCE.relative_to(ROOT.parent)}')


if __name__ == '__main__':
    export()
